def audited_omission_coverage(args, profile, historical, current, historical_check, current_check):
    """Describe checker coverage of the prior independent audit, without forcing it."""
    findings_path = ROOT / "outputs/partition_correctness_audit" / RUN / "all_findings.json"
    if not findings_path.exists():
        return {"status": "prior_audit_fixture_not_available"}
    from run_partition_issue_regression import collect_ids
    from sql_partition_analysis.validation.partition_omissions import _expectations
    selected = [row for row in read_json(findings_path)
                if row["finding_id"] in ("CQ001", "CQ002", "CQ003", "WD-TARGET_FILTER_OWNERSHIP")]
    ids = collect_ids(selected)
    records = {row["id"]: row for row in profile["sqls"]}
    rows = []
    for sid in sorted(ids):
        expected, reasons = _expectations(records[sid]["sql"], current["partition_config"]["tables"])
        rows.append({
            "sql_id": sid, "sql": records[sid]["sql"], "log_count": records[sid]["count"],
            "supported_expectations": [{key: value for key, value in item.items() if not key.startswith("_")}
                                       for item in expected],
            "skip_reasons": reasons,
            "historical_mapping_rows": sum(row["id"] == sid for row in historical["mapping"]),
            "current_mapping_rows": sum(row["id"] == sid for row in current["mapping"]),
            "historical_alerts": [row for row in historical_check["alerts"] if row["sql_id"] == sid],
            "current_alerts": [row for row in current_check["alerts"] if row["sql_id"] == sid],
        })
    write_json(args.output / "prior_audited_omission_coverage.json", rows)
    return {
        "audited_contexts": len(rows),
        "independently_supported_contexts": sum(bool(row["supported_expectations"]) for row in rows),
        "historical_alerted_contexts": sum(bool(row["historical_alerts"]) for row in rows),
        "current_alerted_contexts": sum(bool(row["current_alerts"]) for row in rows),
        "details_file": "prior_audited_omission_coverage.json",
        "interpretation": "The earlier audit included JOIN-only and unknown destination-column cases outside this conservative checker subset.",
    }


def historical_date_identity_compatibility(report, strict_result):
    """Adapt only independently proved DATE values from the legacy archive.

    The former aggregator serialized explicitly typed DATE constants as string
    identities. Keep that historical storage distinction separate from the
    production checker's strict type matching. Never normalize a bare string,
    compact date-looking string, or a value that differs from the expectation.
    """
    adapted = copy.deepcopy(report)
    changes = []
    expected_mappings = collections.defaultdict(set)
    expected_groups = collections.defaultdict(set)
    for alert in strict_result["alerts"]:
        value = alert.get("partition_value", {})
        if value.get("type") == "date":
            key = (alert["sql_id"], alert["table"], alert["expected_role"])
            pair = (alert["partition_field"], value["value"])
            expected_groups[key].add(pair)
            expected_mappings[key + (alert["occurrence"],)].add(pair)

    def upgrade(identity, allowed):
        if not isinstance(identity, list):
            return []
        changed = []
        if len(identity) == 3 and identity[1] == "string" and (identity[0], identity[2]) in allowed:
            identity[1] = "date"
            return [list(identity)]
        for child in identity:
            if isinstance(child, list):
                changed.extend(upgrade(child, allowed))
        return changed

    for row_number, row in enumerate(adapted["mapping"]):
        key = (row["id"], row["table"], row["role"], row["occurrence"])
        changed = upgrade(row.get("partition_identity"), expected_mappings.get(key, set()))
        if changed:
            changes.append({"collection": "mapping", "row": row_number,
                            "sql_ids": [row["id"]], "table": row["table"], "role": row["role"],
                            "occurrence": row["occurrence"], "date_identities": changed})
    # A legacy group may combine explicit DATE and genuinely bare ISO strings.
    # Retain the original string group and add a diagnostic DATE view restricted
    # to SQL IDs with independently proved DATE expectations. This avoids making
    # a bare string disappear when adapting the old merged storage format.
    for row_number, source in enumerate(report["results"]):
        applicable = [sid for sid in source["ids"]
                      if expected_groups.get((sid, source["table"], source["role"]))]
        if not applicable:
            continue
        allowed = set().union(*(expected_groups[(sid, source["table"], source["role"])] for sid in applicable))
        clone = copy.deepcopy(source)
        changed = upgrade(clone.get("partition_identity"), allowed)
        if changed:
            clone["ids"] = applicable
            adapted["results"].append(clone)
            changes.append({"collection": "results_diagnostic_date_view", "row": row_number,
                            "sql_ids": applicable, "table": source["table"], "role": source["role"],
                            "date_identities": changed})
    return adapted, changes


def fault_injections(profile, report, checker, analysis):
    records = {row["id"]: row for row in profile["sqls"]}
    grouped = collections.defaultdict(list)
    for row in report["mapping"]:
        identity = row.get("partition_identity", ())
        if identity and identity[0] == "values" and len(identity[1]) == 1:
            grouped[(row["id"], row["table"], row["occurrence"], row["role"])].append(row)

    def isolated(sid):
        record = copy.deepcopy(records[sid])
        sample = {key: copy.deepcopy(value) for key, value in profile.items() if key != "sqls"}
        sample["sqls"] = [record]
        sample["widths"] = {"archived_context_logs": record["count"]}
        result = {key: copy.deepcopy(value) for key, value in report.items()
                  if key not in ("mapping", "results")}
        result["mapping"] = [copy.deepcopy(row) for row in report["mapping"] if row["id"] == sid]
        result["results"] = [copy.deepcopy(row) for row in report["results"] if sid in row["ids"]]
        for row in result["results"]:
            row["ids"] = [sid]
            row["count"] = record["count"]
        result["metrics"]["source_rows"] = record["count"]
        result["metrics"]["sql_user_contexts"] = 1
        return sample, result

    def alerts_for(result, sid, table):
        return [row for row in result["alerts"]
                if row.get("sql_id", row.get("id")) == sid and row.get("table") == table]

    # Select real archived SQL by evidence characteristics rather than SQL IDs.
    # The checker itself must detect a missing mapping before a sample is used;
    # thus a silently skipped unsupported query cannot make an injection pass.
    selected = {}
    for key, members in sorted(grouped.items()):
        sid, table, occurrence, role = key
        if len(records[sid]["sql"]) > 2500:
            continue
        kind = "in" if len(members) >= 2 else "single"
        if kind in selected:
            continue
        if kind == "in":
            try:
                tree = sqlglot.parse_one(records[sid]["sql"], read="postgres")
                field = members[0]["partition_identity"][1][0][0]
                if not any(isinstance(node.this, exp.Column) and node.this.name == field
                           and len(node.expressions) >= 2 for node in tree.find_all(exp.In)):
                    continue
            except Exception:
                continue
        sample, current = isolated(sid)
        if checker(sample, current)["alerts"]:
            continue
        damaged = copy.deepcopy(current)
        damaged["mapping"] = [row for row in damaged["mapping"]
                              if not (row["table"] == table and row["occurrence"] == occurrence)]
        detected = alerts_for(checker(sample, damaged), sid, table)
        if not detected:
            continue
        selected[kind] = (key, sample, current, members)
        if set(selected) == {"single", "in"}:
            break
    if set(selected) != {"single", "in"}:
        raise ValueError("The checker did not cover suitable archived single-value and IN examples")

    checks = []

    def run(name, key, sample, before, after):
        sid, table, occurrence, role = key
        result = checker(sample, after)
        detected = alerts_for(result, sid, table)
        checks.append({
            "name": name, "sql_id": sid, "table": table, "occurrence": occurrence,
            "sql": sample["sqls"][0]["sql"], "original_log_count": sample["sqls"][0]["count"],
            "original_role": role, "passed": bool(detected), "alerts": detected,
            "source_sql_changed": False,
        })

    key, sample, current, members = selected["single"]
    sid, table, occurrence, role = key
    damaged = copy.deepcopy(current)
    damaged["mapping"] = [row for row in damaged["mapping"]
                          if not (row["table"] == table and row["occurrence"] == occurrence)]
    run("remove corresponding table mapping", key, sample, current, damaged)

    damaged = copy.deepcopy(current)
    for row in damaged["mapping"]:
        if row["table"] == table and row["occurrence"] == occurrence:
            row["role"] = "FAULT_INJECTED_WRONG_ROLE"
    for row in damaged["results"]:
        if row["table"] == table and row["role"] == role:
            row["role"] = "FAULT_INJECTED_WRONG_ROLE"
    run("replace mapping and result access role", key, sample, current, damaged)

    damaged = copy.deepcopy(current)
    damaged["results"] = [row for row in damaged["results"] if not (row["table"] == table and row["role"] == role)]
    run("remove result group while retaining mapping", key, sample, current, damaged)

    removed_details = [row for row in analysis["details"] if row["id"] == sid]
    if not removed_details:
        raise ValueError("Selected archived query has no original table analysis detail")
    damaged_analysis = {
        "metrics": copy.deepcopy(analysis["metrics"]), "details": [],
        "predicates": [row for row in analysis["predicates"] if row["id"] == sid],
        "index": [row for row in analysis["index"] if row["id"] == sid],
        "unresolved": [row for row in analysis["unresolved"] if row[0] == sid],
    }
    damaged = aggregate_accesses(sample, damaged_analysis, PartitionCatalog(report["partition_config"]))
    run("drop analyzer table details before aggregation", key, sample, current, damaged)
    checks[-1]["removed_analysis_details"] = len(removed_details)

    key, sample, current, members = selected["in"]
    sid, table, occurrence, role = key
    removed_identity = members[0]["partition_identity"]
    damaged = copy.deepcopy(current)
    damaged["mapping"] = [row for row in damaged["mapping"]
                          if not (row["table"] == table and row["occurrence"] == occurrence
                                  and row.get("partition_identity") == removed_identity)]
    damaged["results"] = [row for row in damaged["results"]
                          if not (row["table"] == table and row["role"] == role
                                  and row.get("partition_identity") == removed_identity)]
    run("remove one finite IN candidate from mapping and result", key, sample, current, damaged)
    return checks


