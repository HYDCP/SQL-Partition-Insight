def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def sha256_file(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def analysis_dependency_hashes():
    sources = [path for folder in ("partitioning", "analytics", "domain")
               for path in (ROOT / "src/sql_partition_analysis" / folder).rglob("*.py")]
    return {str(path.relative_to(ROOT)): sha256_file(path) for path in sorted(sources)}


def publish_analysis_integrity(output, generation_hashes):
    if generation_hashes != analysis_dependency_hashes():
        raise ValueError("Main analysis generation source no longer matches current dependencies")
    manifest = {
        "version": 1, "source_code_sha256": generation_hashes,
        "artifacts": {name: sha256_file(output / name)
                      for name in ("profile.json", "partition_config.json", "analysis.json", "aggregate.json")},
        "basis": "Main dependency hashes were captured before generation and verified unchanged after generation.",
    }
    write_json(output / "analysis_source_integrity.json", manifest)
    return manifest


def validate_analysis_integrity(output):
    path = output / "analysis_source_integrity.json"
    if not path.exists():
        raise ValueError("Cannot reuse analysis without its generation source/artifact integrity manifest")
    manifest = read_json(path)
    if manifest.get("version") != 1 or manifest.get("source_code_sha256") != analysis_dependency_hashes():
        raise ValueError("Cannot reuse analysis generated by different main dependencies")
    required = {"profile.json", "partition_config.json", "analysis.json", "aggregate.json"}
    if set(manifest.get("artifacts", {})) != required:
        raise ValueError("Cannot reuse an incomplete analysis artifact integrity manifest")
    for name, expected in manifest["artifacts"].items():
        if sha256_file(output / name) != expected:
            raise ValueError("Cannot reuse changed analysis artifact: " + name)
    return manifest


def archive_json(archive, basename):
    names = [name for name in archive.namelist() if Path(name).name == basename]
    if len(names) != 1:
        raise ValueError("Archive must contain exactly one " + basename)
    raw = archive.read(names[0])
    return json.loads(raw), {"name": names[0], "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}


