def check_complete_profile(profile, report, workers, label):
    from sql_partition_analysis.validation.partition_omissions import check_partition_omissions
    if workers == 1:
        def progress(done, total):
            if done % 10000 == 0 or done == total:
                print("Checking {}: {}/{} contexts".format(label, done, total), flush=True)
        return check_partition_omissions(profile, report, progress=progress)
    chunks = split_records(profile["sqls"], workers)
    outputs = []
    context = multiprocessing.get_context("spawn")
    with concurrent.futures.ProcessPoolExecutor(
            max_workers=workers, mp_context=context, initializer=omission_worker_init, initargs=(report,)) as pool:
        futures = []
        for records in chunks:
            part = {key: value for key, value in profile.items() if key != "sqls"}
            part["sqls"] = records
            part["widths"] = {"archived_context_logs": sum(row["count"] for row in records)}
            futures.append(pool.submit(omission_worker_check, part))
        for future in concurrent.futures.as_completed(futures):
            outputs.append(future.result())
            print("Checking {}: {}/{} chunks, {} contexts complete".format(
                label, len(outputs), len(chunks), sum(row["metrics"]["sql_contexts"] for row in outputs)), flush=True)
    if any(row["checker_version"] != outputs[0]["checker_version"]
           or row["coverage"] != outputs[0]["coverage"] for row in outputs):
        raise ValueError("Independent checker workers returned inconsistent versions or coverage definitions")
    result = {key: copy.deepcopy(value) for key, value in outputs[0].items() if key not in ("alerts", "metrics")}
    result["metrics"] = {}
    for key in outputs[0]["metrics"]:
        if key == "skip_reason_counts":
            counts = collections.Counter()
            for output in outputs:
                counts.update(output["metrics"][key])
            result["metrics"][key] = dict(sorted(counts.items()))
        else:
            result["metrics"][key] = sum(output["metrics"][key] for output in outputs)
    order = {record["id"]: position for position, record in enumerate(profile["sqls"])}
    result["alerts"] = sorted([row for output in outputs for row in output["alerts"]],
                              key=lambda row: (order[row["sql_id"]], row["occurrence"]))
    if result["metrics"]["sql_contexts"] != len(profile["sqls"]):
        raise ValueError("Independent checker chunk merge changed context counts")
    return result


def analyze_complete_profile(profile, config, workers):
    if workers == 1:
        return analyze_profile(profile, PartitionCatalog(config))
    chunks = split_records(profile["sqls"], workers)
    outputs = []
    context = multiprocessing.get_context("spawn")
    with concurrent.futures.ProcessPoolExecutor(
            max_workers=workers, mp_context=context, initializer=worker_init, initargs=(config,)) as pool:
        futures = []
        for records in chunks:
            part = {key: value for key, value in profile.items() if key != "sqls"}
            part["sqls"] = records
            part["widths"] = {"archived_context_logs": sum(row["count"] for row in records)}
            futures.append(pool.submit(worker_analyze, part))
        for future in concurrent.futures.as_completed(futures):
            result = future.result()
            outputs.append(result)
            print("Parsed {}/{} chunks; {} SQL/user contexts complete".format(
                len(outputs), len(chunks), sum(len(item["index"]) for item in outputs)), flush=True)
    return merge_results(profile, outputs)


def prepare(args):
    args.output.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(args.archive) as archive:
        profile, profile_member = archive_json(archive, "profile.json")
        config, config_member = archive_json(archive, "partition_config.json")
        historical, aggregate_member = archive_json(archive, "aggregate.json")
        historical_analysis, analysis_member = archive_json(archive, "analysis.json")
    ids = [row["id"] for row in profile["sqls"]]
    counts = sum(row["count"] for row in profile["sqls"])
    if len(set(ids)) != len(ids) or counts != sum(profile["widths"].values()):
        raise ValueError("Archived profile SQL IDs/counts are inconsistent")
    if set(row["id"] for row in historical_analysis["index"]) != set(ids):
        raise ValueError("Archived profile/analysis SQL IDs disagree")
    if historical["metrics"]["source_rows"] != counts:
        raise ValueError("Archived aggregate/profile source counts disagree")
    PartitionCatalog(config)
    metadata = {
        "archive": str(args.archive.resolve()), "archive_sha256": sha256_file(args.archive),
        "archive_bytes": args.archive.stat().st_size,
        "members": [profile_member, config_member, aggregate_member, analysis_member],
        "contexts": len(ids), "source_rows": counts,
        "raw_distinct_messages": len(set(row["sql"] for row in profile["sqls"])),
        "catalog_tables": len(config["tables"]),
        "raw_observations_reconstructed": False, "execution_success_verified": False,
        "old_observations_used": False,
        "observation_limit": "The archived observations contain only old matched accesses; they cannot validate newly recovered references.",
    }
    write_json(args.output / "input_integrity.json", metadata)
    write_json(args.output / "profile.json", profile)
    write_json(args.output / "partition_config.json", config)
    write_json(args.output / "historical_aggregate.json", historical)
    return profile, config, historical, metadata


def check_alert_integrity(profile, report, result):
    records = {row["id"]: row for row in profile["sqls"]}
    config = report["partition_config"]["tables"]
    failures = []
    for alert in result["alerts"]:
        sid = alert.get("sql_id", alert.get("id"))
        record = records.get(sid)
        if record is None:
            failures.append({"reason": "unknown SQL ID", "alert": alert})
            continue
        if alert.get("table") not in config:
            failures.append({"reason": "alert does not reference an explicitly configured table", "sql_id": sid})
        elif alert.get("partition_field") not in config[alert["table"]]["partition_columns"]:
            failures.append({"reason": "alert partition field is not in the table configuration", "sql_id": sid})
        missing = alert.get("missing_outputs", [])
        if not missing or not set(missing).issubset({"mapping", "results"}):
            failures.append({"reason": "alert has no valid missing output location", "sql_id": sid})
        for alert_key, record_key in (("sql", "sql"), ("user_name", "user_name"),
                                      ("log_count", "count"), ("first_record", "first_record"),
                                      ("first_time", "first_time"), ("last_time", "last_time")):
            if alert_key not in alert or alert[alert_key] != record[record_key]:
                failures.append({"reason": "source metadata changed", "sql_id": sid, "field": alert_key})
    return failures


